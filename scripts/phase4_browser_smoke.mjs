// Run through the browser-automation skill against scripts.smoke_server only.
// Creates synthetic data in its disposable database, not the user's library.
export default async function run(page, ui) {
  const checks = [];
  const apiFailures = [];
  page.on('response', response => {
    if (response.url().includes('/api/') && response.status() >= 400 && ![401, 404].includes(response.status())) {
      apiFailures.push({ path: new URL(response.url()).pathname, status: response.status() });
    }
  });
  const assert = (condition, message) => { if (!condition) throw new Error(message); checks.push(message); };
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.getByRole('button', { name: 'BookWise home' }).waitFor();
  await ui.snapshot();
  await page.getByRole('button', { name: 'Join', exact: true }).click();
  await ui.snapshot();
  const username = `phase4_qa_${Date.now()}`;
  await page.getByLabel('Username', { exact: true }).fill(username);
  await page.getByLabel('Email', { exact: true }).fill(`${username}@example.invalid`);
  await page.getByLabel('Password', { exact: true }).fill(`QA-only-${crypto.randomUUID()}`);
  await page.getByRole('button', { name: 'Create account', exact: true }).click();
  await page.getByRole('heading', { name: 'Tell us what you love' }).waitFor();
  await ui.snapshot();
  await page.getByRole('button', { name: "I'll do this later" }).click();
  assert(await page.getByRole('dialog').count() === 0, 'onboarding dismissal does not open an invalid book');
  const cookies = await page.context().cookies();
  assert(cookies.some(cookie => cookie.name === 'bookwise_access_token' && cookie.httpOnly), 'HttpOnly session cookie issued');
  const nav = page.getByRole('navigation', { name: 'Primary navigation', exact: true });
  await nav.getByRole('button', { name: 'Reading Room', exact: true }).click();
  await page.getByLabel('New shelf name').waitFor();
  await ui.snapshot();
  await page.getByLabel('New shelf name').fill('Smoke shelf');
  await page.getByRole('button', { name: 'Create shelf', exact: true }).click();
  await page.getByRole('heading', { name: 'Smoke shelf', exact: true }).waitFor();
  checks.push('custom shelf created');
  await nav.getByRole('button', { name: 'For You', exact: true }).click();
  await page.getByRole('button', { name: /^View / }).first().waitFor({ timeout: 60000 });
  await ui.snapshot();
  await page.getByLabel('Recommendation balance', { exact: true }).selectOption('experiment');
  await page.getByRole('button', { name: 'Save settings', exact: true }).click();
  await page.getByText(/Source: experiment/).waitFor({ timeout: 60000 });
  assert(await page.getByLabel('Book length', { exact: true }).isDisabled(), 'length control accurately reports missing metadata');
  const first = page.getByRole('article').first();
  const firstTitle = await first.getAttribute('aria-label');
  assert((await first.innerText()).includes('Why this book'), 'evidence-backed explanations displayed');
  await first.getByRole('button', { name: /^View / }).click();
  const dialog = page.getByRole('dialog');
  await dialog.getByLabel('Progress (%)').waitFor();
  await ui.snapshot();
  await dialog.getByLabel('Progress (%)').fill('25');
  await dialog.getByRole('button', { name: 'Save progress', exact: true }).click();
  await dialog.getByText('Reading progress saved.', { exact: true }).waitFor();
  await dialog.getByLabel('Private note or quote').fill('Synthetic QA note, never part of a public list.');
  await dialog.getByRole('button', { name: 'Save private entry', exact: true }).click();
  await dialog.getByText('Private entry saved.', { exact: true }).waitFor();
  await dialog.getByRole('button', { name: /^Follow / }).first().click();
  await dialog.getByRole('button', { name: /^Unfollow / }).first().waitFor();
  await ui.snapshot();
  await dialog.getByRole('button', { name: /Add to Smoke shelf/ }).click();
  await dialog.getByRole('button', { name: /Remove from Smoke shelf/ }).waitFor();
  await dialog.getByRole('button', { name: 'Add to comparison', exact: true }).click();
  await dialog.getByRole('button', { name: 'Close book details', exact: true }).click();
  checks.push('progress, private note, followed author, shelf membership and comparison saved');
  await page.getByRole('button', { name: /^View / }).nth(1).click();
  await page.getByRole('button', { name: 'Add to comparison', exact: true }).click();
  await page.getByRole('button', { name: 'Close book details', exact: true }).click();
  await page.getByRole('button', { name: 'Compare books (2/4)', exact: true }).click();
  assert(await page.getByRole('region', { name: 'Comparison table', exact: true }).isVisible(), 'two-book comparison renders');
  await page.getByRole('button', { name: 'Close comparison', exact: true }).click();
  const before = await page.getByRole('article').count();
  await page.getByRole('button', { name: 'Load more', exact: true }).click();
  await page.waitForFunction(count => document.querySelectorAll('article[aria-label]').length > count, before);
  checks.push('Load more appends recommendations');
  await nav.getByRole('button', { name: 'Reading Room', exact: true }).click();
  await page.getByRole('button', { name: `Resume ${firstTitle}`, exact: true }).waitFor();
  await ui.snapshot();
  await page.getByLabel('List title', { exact: true }).fill('QA shared recommendations');
  await page.getByLabel('Books from shelf', { exact: true }).selectOption({ label: 'Smoke shelf' });
  await page.getByRole('button', { name: 'Save private list', exact: true }).click();
  await page.getByRole('button', { name: 'Publish QA shared recommendations', exact: true }).click();
  const link = page.getByRole('link', { name: /\?list=/ });
  await link.waitFor();
  const shareUrl = await link.getAttribute('href');
  await page.goto(shareUrl);
  await page.getByRole('heading', { name: 'QA shared recommendations', exact: true }).waitFor();
  assert(!(await page.locator('body').innerText()).includes('Synthetic QA note'), 'published list never contains private notes');
  await nav.getByRole('button', { name: 'Reading Room', exact: true }).click();
  const onboarding = page.getByRole('button', { name: "I'll do this later" });
  if (await onboarding.isVisible()) await onboarding.click();
  await page.getByRole('button', { name: 'Revoke link for QA shared recommendations', exact: true }).click();
  await page.getByText('Share link revoked. The old link no longer opens this list.', { exact: true }).waitFor();
  await page.goto(shareUrl);
  await page.getByRole('heading', { name: 'Shared list unavailable', exact: true }).waitFor();
  checks.push('explicit publication works and revocation invalidates the old link');
  await page.getByRole('button', { name: 'Switch to dark mode' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'Switch to light mode' }).waitFor();
  checks.push('dark mode and cookie session survive reload');
  await page.setViewportSize({ width: 390, height: 844 });
  const mobile = page.getByRole('navigation', { name: 'Mobile navigation', exact: true });
  await mobile.getByRole('button', { name: 'For You', exact: true }).click();
  if (await onboarding.isVisible()) await onboarding.click();
  await page.getByRole('button', { name: /^View / }).first().waitFor({ timeout: 60000 });
  await ui.snapshot();
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth + 2);
  assert(!overflow, '390px mobile layout has no horizontal page overflow');
  assert(await mobile.isVisible(), 'mobile navigation is visible with labeled destinations');
  assert(apiFailures.length === 0, 'no unexpected API errors in smoke flow');
  return { checks, apiFailures, syntheticDataOnly: true };
}
